import { afterEach, describe, expect, it, vi } from 'vitest'
import { ActivityVisibility, shouldRevealForSnapshot } from './activity-policy'

afterEach(() => vi.useRealTimers())

describe('surrounding UI activity policy', () => {
  it('hides after three seconds without activity, including stationary pointer', () => {
    vi.useFakeTimers()
    const changed = vi.fn()
    const activity = new ActivityVisibility(changed)
    activity.reveal()
    vi.advanceTimersByTime(2999)
    expect(activity.visible).toBe(true)
    vi.advanceTimersByTime(1)
    expect(activity.visible).toBe(false)
    expect(changed).toHaveBeenLastCalledWith(false)
    activity.dispose()
  })
  it('restarts idle delay on pointer movement or keyboard intent', () => {
    vi.useFakeTimers()
    const changed = vi.fn()
    const activity = new ActivityVisibility(changed)
    activity.reveal()
    vi.advanceTimersByTime(2500)
    activity.reveal()
    vi.advanceTimersByTime(2500)
    expect(activity.visible).toBe(true)
    vi.advanceTimersByTime(500)
    expect(activity.visible).toBe(false)
    activity.dispose()
  })
  it('does not restart idle delay for recurring non-pinning chat snapshots', () => {
    vi.useFakeTimers()
    const activity = new ActivityVisibility(vi.fn())
    activity.reveal()
    vi.advanceTimersByTime(2000)
    activity.setPinned(false)
    vi.advanceTimersByTime(1000)
    expect(activity.visible).toBe(false)
    activity.dispose()
  })
  it('keeps an active interaction pinned until it finishes', () => {
    vi.useFakeTimers()
    const activity = new ActivityVisibility(vi.fn())
    activity.setPinned(true)
    vi.advanceTimersByTime(9000)
    expect(activity.visible).toBe(true)
    activity.setPinned(false)
    vi.advanceTimersByTime(3000)
    expect(activity.visible).toBe(false)
    activity.dispose()
  })
  it('does not pin empty UI for idle or armed snapshots', () => {
    expect(shouldRevealForSnapshot({ busy: false, stopping: false, voice: { state: 'armed' } })).toBe(false)
    expect(shouldRevealForSnapshot({ busy: false, stopping: false })).toBe(false)
  })
  it('keeps controls revealed during consequential activity', () => {
    expect(shouldRevealForSnapshot({ busy: true, stopping: false })).toBe(true)
    expect(shouldRevealForSnapshot({ busy: false, stopping: false, approval: {} })).toBe(true)
    expect(shouldRevealForSnapshot({ busy: false, stopping: false, voice: { state: 'capturing' } })).toBe(true)
    expect(shouldRevealForSnapshot({ busy: false, stopping: false, voice: { state: 'speaking' } })).toBe(true)
    expect(shouldRevealForSnapshot({ busy: false, stopping: false, voice: { state: 'error' } })).toBe(true)
  })
})
