import { readFileSync } from 'node:fs'
import { expect, test } from 'vitest'

test('draft activity crosses only a boolean IPC and follow-up has visible listening and Stop controls', () => {
  const main = readFileSync('src/main/index.ts', 'utf8')
  const preload = readFileSync('src/preload/index.ts', 'utf8')
  const renderer = readFileSync('src/renderer/main.ts', 'utf8')
  expect(preload).toContain("ipcRenderer.send('orb:text-activity', hasDraft)")
  expect(main).toContain("channel === 'text-activity'")
  expect(main).toContain('voice?.textActivity(false)')
  expect(renderer).toContain("input.addEventListener('input'")
  expect(renderer).toContain('!voice.followupActive')
})

test('three-state Voice is one accessible control with listening status and trusted validated IPC', () => {
  const main = readFileSync('src/main/index.ts', 'utf8')
  const preload = readFileSync('src/preload/index.ts', 'utf8')
  const renderer = readFileSync('src/renderer/main.ts', 'utf8')
  expect(main).toContain('validVoiceMode(args[0])')
  expect(main).toContain('voice?.cycleMode()')
  expect(preload).toContain("ipcRenderer.send('orb:voice-mode')")
  expect(renderer).not.toContain('activationButton')
  expect(renderer).not.toContain('muteButton')
  expect(renderer).toContain("voiceButton.setAttribute('aria-pressed'")
  expect(renderer).toContain('voiceButton.textContent = voiceModeLabel(currentMode)')
  expect(renderer).toContain('voiceModeDescription(currentMode, assistant.wakePhrase)')
  expect(renderer).not.toContain("? 'Active' : voice?.enabled ? 'Voice' : 'Voice off'")
})

test('Electron owns a local sidecar and exposes only narrow voice controls, no raw audio IPC', () => {
  const main = readFileSync('src/main/index.ts', 'utf8')
  const preload = readFileSync('src/preload/index.ts', 'utf8')
  const renderer = readFileSync('src/renderer/main.ts', 'utf8')
  expect(main).toContain('new SidecarClient(')
  expect(main).toContain("globalShortcut.register('Control+Alt+M'")
  expect(main).toContain('sidecar.close()')
  expect(preload).toContain("ipcRenderer.send('orb:ptt', down)")
  expect(renderer).toContain("button.setPointerCapture(event.pointerId)")
  expect(renderer).toContain('orb.setLevel(')
  expect(preload).not.toMatch(/token|WebSocket|pcm|audioBuffer|API_SERVER_KEY/)
  expect(main).toContain("mock && process.argv.includes('--voice-smoke')")
  expect(main).toContain('moving || holding')
  expect(main).toContain("syntheticAudio: mock && process.argv.includes('--voice-smoke')")
  expect(readFileSync('scripts/voice-smoke.mjs', 'utf8')).toContain("dataset.syntheticAudio==='true'")
})

test('enrollment has an explicit narrow action and app-owned profile path with synthetic isolation', () => {
  const main = readFileSync('src/main/index.ts', 'utf8')
  const preload = readFileSync('src/preload/index.ts', 'utf8')
  const renderer = readFileSync('src/renderer/main.ts', 'utf8')
  const server = readFileSync('sidecar/server.py', 'utf8')
  expect(main).toContain("channel === 'enroll-voice'")
  expect(main).toContain("join(app.getPath('userData'), 'voice-profiles', 'registered.json')")
  expect(preload).toContain("ipcRenderer.send('orb:enroll-voice')")
  expect(renderer).toContain('Enroll my voice locally')
  expect(renderer).toContain('voice.enrolling')
  expect(server).toContain('ORB_VOICE_PROFILE')
  expect(server).toContain('engine.speaker_status()')
})
